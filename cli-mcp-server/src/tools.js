export function createToolCaller({ run = runLarkCli, schedulerStats = getSchedulerStats, now = () => Date.now() } = {}) {
  const pendingAuthorizations = new Map();

  return async function callTool(name, args = {}) {
    validateToolArguments(name, args);
    prunePendingAuthorizations(pendingAuthorizations, now());

    switch (name) {
      case "lark_runtime_status":
        return jsonContent({ ok: true, name: SERVER_NAME, version: SERVER_VERSION, scheduler: schedulerStats() });
      case "lark_profile_list":
        return resultContent(requireSuccess(await run(["profile", "list"])));
      case "lark_skills_list":
        return resultContent(requireSuccess(await run(["skills", "list"])));
      case "lark_skill_read": {
        const argv = ["skills", "read", args.skill];
        if (args.path) {
          if (!isSafeRelativePath(args.path) || args.path.startsWith("-")) throw new Error("path must be a safe relative path");
          argv.push(args.path);
        }
        const result = requireSuccess(await run(argv));
        return jsonContent({ skill: args.skill, path: args.path ?? null, text: result.stdout });
      }
      case "lark_event_list":
        return resultContent(requireSuccess(await run(["event", "list", "--json"])));
      case "lark_event_schema":
        return resultContent(requireSuccess(await run(["event", "schema", args.key, "--json"])));
      default:
        break;
    }

    if (!EXECUTION_REQUIRED.every((key) => key in args)) throw new Error(`Unknown tool: ${name}`);

    const preflight = await verifyExecutionContext(run, args, { allowUnavailableUser: name === "lark_auth_login_start" });
    const prefix = ["--profile", args.profile];

    switch (name) {
      case "lark_auth_status":
        return jsonContent(redactAuthStatus(preflight.auth));
      case "lark_auth_login_start": {
        if (args.identity !== "user") throw new Error("lark_auth_login_start supports identity=user only");
        if (!hasAuthScopeSelection(args)) throw new Error("lark_auth_login_start requires scope, domain, or recommend=true");
        const argv = [...prefix, "auth", "login", "--no-wait", "--json"];
        pushOptional(argv, "--scope", args.scope);
        pushRepeated(argv, "--domain", args.domain);
        if (args.recommend === true) argv.push("--recommend");
        pushRepeated(argv, "--exclude", args.exclude);

        const result = requireSuccess(await run(argv));
        const payload = result.parsedStdout ?? parseJsonLines(result.stdout);
        const deviceCode = findNamedString(payload, ["device_code", "deviceCode"]);
        const verificationUrl = findNamedString(payload, ["verification_url", "verification_uri_complete", "verificationUrl"]);
        const userCode = findNamedString(payload, ["user_code", "userCode"]);
        if (!deviceCode || !verificationUrl) throw new Error("lark-cli did not return the required device authorization fields");

        const authorizationHandle = randomUUID();
        pendingAuthorizations.set(authorizationHandle, {
          deviceCode,
          context: args.context,
          profile: args.profile,
          expectedAppId: args.expectedAppId,
          identity: args.identity,
          expiresAt: now() + AUTHORIZATION_TTL_MS
        });

        let asciiQr = null;
        if (args.asciiQr === true) {
          const qrResult = requireSuccess(await run([...prefix, "auth", "qrcode", verificationUrl, "--ascii"]));
          asciiQr = qrResult.stdout.trimEnd();
        }
        return jsonContent({ authorizationHandle, verificationUrl, userCode: userCode ?? null, expiresInSeconds: 600, asciiQr });
      }
      case "lark_auth_login_complete": {
        const pending = pendingAuthorizations.get(args.authorizationHandle);
        if (!pending) throw new Error("authorization handle is invalid or expired");
        if (pending.expiresAt <= now()) {
          pendingAuthorizations.delete(args.authorizationHandle);
          throw new Error("authorization handle is invalid or expired");
        }
        if (!sameExecution(pending, args)) throw new Error("authorization handle does not match the frozen execution context");
        if (pending.inUse) throw new Error("authorization handle is already being completed");
        pending.inUse = true;
        try {
          const result = requireSuccess(
            await run([...prefix, "auth", "login", "--device-code", pending.deviceCode, "--json"], { timeoutMs: 180_000 })
          );
          pendingAuthorizations.delete(args.authorizationHandle);
          return resultContent(result, redactSensitivePayload);
        } catch (error) {
          pending.inUse = false;
          throw error;
        }
      }
      case "lark_doctor_offline":
        return resultContent(requireSuccess(await run([...prefix, "doctor", "--offline"])));
      case "lark_drive_inspect": {
        const argv = [...prefix, "drive", "+inspect", "--json", "--url", args.url];
        pushOptional(argv, "--type", args.type);
        argv.push("--as", args.identity);
        return resultContent(requireSuccess(await run(argv)));
      }
      case "lark_drive_search": {
        if (args.identity !== "user") throw new Error("lark_drive_search supports identity=user only");
        const argv = [...prefix, "drive", "+search", "--json"];
        pushOptional(argv, "--query", args.query ?? "");
        pushOptional(argv, "--doc-types", args.docTypes);
        pushOptional(argv, "--sort", args.sort);
        pushOptional(argv, "--page-size", args.pageSize);
        argv.push("--as", "user");
        return resultContent(requireSuccess(await run(argv)));
      }
      case "lark_docs_fetch": {
        const argv = [...prefix, "docs", "+fetch", "--json", "--doc", args.doc];
        pushOptional(argv, "--scope", args.scope);
        pushOptional(argv, "--detail", args.detail);
        pushOptional(argv, "--doc-format", args.docFormat);
        pushOptional(argv, "--keyword", args.keyword);
        pushOptional(argv, "--start-block-id", args.startBlockId);
        pushOptional(argv, "--end-block-id", args.endBlockId);
        pushOptional(argv, "--max-depth", args.maxDepth);
        argv.push("--as", args.identity);
        return resultContent(requireSuccess(await run(argv, { timeoutMs: 180_000 })));
      }
      case "lark_event_consume_bounded": {
        const maxEvents = Number.isInteger(args.maxEvents) ? args.maxEvents : 1;
        const timeout = args.timeout ?? "30s";
        if (maxEvents <= 0 && /^0(?:ms|s|m|h)$/.test(timeout)) {
          throw new Error("lark_event_consume_bounded requires maxEvents > 0 or a non-zero timeout");
        }
        const argv = [
          ...prefix,
          "event",
          "consume",
          args.key,
          "--max-events",
          String(maxEvents),
          "--timeout",
          timeout,
          "--as",
          args.identity,
          ...buildParams(args.params)
        ];
        pushOptional(argv, "--jq", args.jq);
        const result = requireSuccess(await run(argv, { timeoutMs: durationToMs(timeout, 30_000) + 15_000 }));
        const events = parseJsonLines(result.stdout);
        return jsonContent({ ok: true, eventKey: args.key, count: events.length, events, durationMs: result.durationMs });
      }
      case "lark_api_dry_run": {
        const argv = [...prefix, "api", args.method, args.path, "--dry-run", "--json", "--as", args.identity];
        if (args.params !== undefined) argv.push("--params", JSON.stringify(args.params));
        if (args.data !== undefined) argv.push("--data", JSON.stringify(args.data));
        return resultContent(requireSuccess(await run(argv)));
      }
      default:
        throw new Error(`Unknown tool: ${name}`);
    }
  };
}

export const callTool = createToolCaller();

async function verifyExecutionContext(run, args, { allowUnavailableUser = false } = {}) {
  if (!matchesProcessContext(args.context)) {
    throw new Error(`execution_context_mismatch: requested ${args.context} context is not available in this MCP process`);
  }

  const prefix = ["--profile", args.profile];
  const configResult = requireSuccess(await run([...prefix, "config", "show"]));
  const config = requireObjectPayload(configResult, "config show");
  const whoamiResult = requireSuccess(await run([...prefix, "whoami", "--json", "--as", args.identity]));
  const whoami = requireObjectPayload(whoamiResult, "whoami");
  const authResult = requireSuccess(await run([...prefix, "auth", "status", "--json", "--verify"]));
  const auth = requireObjectPayload(authResult, "auth status");

  const actualProfiles = [config.profile, whoami.profile].filter(Boolean);
  if (actualProfiles.length < 2 || actualProfiles.some((profile) => profile !== args.profile)) {
    throw new Error("execution_context_mismatch: selected profile did not match preflight evidence");
  }
  const actualAppIds = [config.appId, whoami.appId, auth.appId].filter(Boolean);
  if (actualAppIds.length < 3 || actualAppIds.some((appId) => appId !== args.expectedAppId)) {
    throw new Error("execution_context_mismatch: expected App did not match preflight evidence");
  }
  if (whoami.identity !== args.identity) {
    throw new Error("execution_context_mismatch: selected identity did not match preflight evidence");
  }

  const identityStatus = auth.identities?.[args.identity];
  const identityAvailable = whoami.available === true || identityStatus?.available === true;
  const identityVerified = identityStatus?.verified ?? (auth.identity === args.identity ? auth.verified : undefined);
  if ((!identityAvailable || identityVerified !== true) && !(allowUnavailableUser && args.identity === "user")) {
    throw new Error("identity_unverified: selected identity is not ready and verified");
  }
  return { config, whoami, auth };
}

function matchesProcessContext(context) {
  const channelEvidence = [
    process.env.LARK_CHANNEL === "1",
    Boolean(process.env.LARK_CHANNEL_PROFILE),
    Boolean(process.env.LARK_CHANNEL_CONFIG)
  ].some(Boolean);
  return context === (channelEvidence ? "channel" : "system");
}

function requireObjectPayload(result, label) {
  const payload = result.parsedStdout;
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) {
    throw new Error(`identity_unverified: ${label} did not return structured JSON`);
  }
  return payload;
}

function validateToolArguments(name, args) {
  const tool = TOOLS.find((candidate) => candidate.name === name);
  if (!tool) throw new Error(`Unknown tool: ${name}`);
  if (!args || typeof args !== "object" || Array.isArray(args)) throw new Error(`${name} arguments must be an object`);

  const schema = tool.inputSchema;
  const properties = schema.properties ?? {};
  for (const required of schema.required ?? []) {
    if (!(required in args)) throw new Error(`${name}.${required} is required`);
  }
  if (schema.additionalProperties === false) {
    for (const key of Object.keys(args)) {
      if (!(key in properties)) throw new Error(`${name}.${key} is not allowed`);
    }
  }
  for (const [key, value] of Object.entries(args)) validateValue(`${name}.${key}`, value, properties[key]);
}

function validateValue(label, value, schema) {
  if (!schema) return;
  if (schema.oneOf) {
    const matches = schema.oneOf.filter((candidate) => valueMatches(value, candidate));
    if (matches.length !== 1) throw new Error(`${label} does not match the declared schema`);
    validateValue(label, value, matches[0]);
    return;
  }
  if (!valueMatches(value, schema)) throw new Error(`${label} does not match the declared schema`);
  if (typeof value === "string") {
    if (schema.minLength !== undefined && value.length < schema.minLength) throw new Error(`${label} is too short`);
    if (schema.maxLength !== undefined && value.length > schema.maxLength) throw new Error(`${label} is too long`);
    if (schema.pattern && !new RegExp(schema.pattern).test(value)) throw new Error(`${label} has an invalid format`);
  }
  if (typeof value === "number") {
    if (schema.minimum !== undefined && value < schema.minimum) throw new Error(`${label} is below minimum`);
    if (schema.maximum !== undefined && value > schema.maximum) throw new Error(`${label} exceeds maximum`);
  }
  if (Array.isArray(value)) {
    if (schema.maxItems !== undefined && value.length > schema.maxItems) throw new Error(`${label} has too many items`);
    for (const [index, item] of value.entries()) validateValue(`${label}[${index}]`, item, schema.items);
  }
  if (schema.enum && !schema.enum.includes(value)) throw new Error(`${label} is not an allowed value`);
  if (schema.type === "object" && value && typeof value === "object" && !Array.isArray(value)) {
    const entries = Object.entries(value);
    if (schema.maxProperties !== undefined && entries.length > schema.maxProperties) throw new Error(`${label} has too many properties`);
    for (const [key, item] of entries) {
      if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
        validateValue(`${label}.${key}`, item, schema.additionalProperties);
      }
    }
  }
}

function valueMatches(value, schema) {
  switch (schema?.type) {
    case "string": return typeof value === "string";
    case "boolean": return typeof value === "boolean";
    case "integer": return Number.isInteger(value);
    case "array": return Array.isArray(value);
    case "object": return Boolean(value) && typeof value === "object" && !Array.isArray(value);
    default: return true;
  }
}

function pushOptional(argv, flag, value) {
  if (value === undefined || value === null || value === "") return;
  argv.push(flag, String(value));
}

function pushRepeated(argv, flag, value) {
  if (value === undefined || value === null || value === "") return;
  for (const item of Array.isArray(value) ? value : [value]) {
    if (item !== undefined && item !== null && item !== "") argv.push(flag, String(item));
  }
}

function findNamedString(value, names) {
  if (!value || typeof value !== "object") return null;
  if (!Array.isArray(value)) {
    for (const name of names) {
      if (typeof value[name] === "string" && value[name]) return value[name];
    }
  }
  for (const child of Object.values(value)) {
    if (!child || typeof child !== "object") continue;
    const found = findNamedString(child, names);
    if (found) return found;
  }
  return null;
}

function durationToMs(value, fallbackMs) {
  const match = String(value ?? "").trim().match(/^(\d+)(ms|s|m|h)$/);
  if (!match) return fallbackMs;
  const amount = Number(match[1]);
  return amount * ({ ms: 1, s: 1000, m: 60_000, h: 3_600_000 }[match[2]] ?? 1);
}

function hasAuthScopeSelection(args) {
  return Boolean(args.scope || args.domain || args.recommend === true);
}

function sameExecution(left, right) {
  return ["context", "profile", "expectedAppId", "identity"].every((key) => left[key] === right[key]);
}

function prunePendingAuthorizations(pendingAuthorizations, currentTime) {
  for (const [handle, pending] of pendingAuthorizations) {
    if (pending.expiresAt <= currentTime) pendingAuthorizations.delete(handle);
  }
}

function jsonContent(payload) {
  return {
    content: [{ type: "text", text: JSON.stringify(payload, null, 2) }],
    structuredContent: payload
  };
}
