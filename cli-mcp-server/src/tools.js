const PROFILE_PATTERN = "^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$";
const APP_ID_PATTERN = "^[A-Za-z0-9][A-Za-z0-9_-]{5,127}$";
const EVENT_KEY_PATTERN = "^[A-Za-z0-9][A-Za-z0-9._:-]{0,255}$";
const POSITIONAL_PATTERN = "^(?!-)[^\\s\\0]+$";
const TOKEN_OR_URL_PATTERN = "^(?!-)(?:https?://[^\\s\\0]+|[A-Za-z0-9][A-Za-z0-9._~:/?#[\\]@!$&'()*+,;=%-]*)$";
const AUTHORIZATION_TTL_MS = 10 * 60_000;

const EXECUTION_PROPERTIES = {
  context: {
    type: "string",
    enum: ["channel", "system"],
    description: "Caller-selected execution/config context. It is verified against the process binding, not inferred from it."
  },
  profile: {
    type: "string",
    pattern: PROFILE_PATTERN,
    description: "Existing lark-cli profile inside the selected execution context."
  },
  expectedAppId: {
    type: "string",
    pattern: APP_ID_PATTERN,
    description: "App ID frozen from an independent caller or profile-selection anchor."
  },
  identity: {
    type: "string",
    enum: ["user", "bot"],
    description: "Identity that must remain selected through preflight and execution."
  }
};

const EXECUTION_REQUIRED = ["context", "profile", "expectedAppId", "identity"];

function executionSchema(properties = {}, required = []) {
  return {
    type: "object",
    additionalProperties: false,
    required: [...EXECUTION_REQUIRED, ...required],
    properties: { ...EXECUTION_PROPERTIES, ...properties }
  };
}

